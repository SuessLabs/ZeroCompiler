#Requires -Version 7.0
[CmdletBinding()]
param(
  [ValidateSet('Debug', 'Release')][string]$Configuration = 'Release',
  [ValidateSet('win-x64', 'linux-x64', 'linux-arm64', 'osx-x64', 'osx-arm64')][string]$Runtime,
  [ValidateSet('Size', 'Speed')][string]$OptimizationPreference = 'Size',
  [ValidateNotNullOrEmpty()][Alias('Version')][string]$CompilerVersion,
  [ValidateNotNullOrEmpty()][string]$IdeVersion
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'installer/dependencies.ps1')
if (!$Runtime) {
  $Runtime = Get-ZeroHostRuntime }

$hostPlatform = (Get-ZeroHostRuntime).Split('-')[0]
if (!$Runtime.StartsWith("$hostPlatform-")) {
  throw 'Publish on the target operating system; Native AOT requires a native toolchain.' }

# Use child processes so build.ps1's explicit exit codes cannot terminate this script.
$powerShell = Join-Path $PSHOME $(if ($IsWindows) { 'pwsh.exe' } else { 'pwsh' })
& $powerShell -NoProfile -File (Join-Path $PSScriptRoot 'ud.ps1')
if ($LASTEXITCODE -ne 0) {
  throw "Dependency setup failed (exit $LASTEXITCODE)." }

$buildArguments = @('-Configuration', $Configuration, '-Runtime', $Runtime, '-OptimizationPreference', $OptimizationPreference)
if ($CompilerVersion) {
  $buildArguments += @('-CompilerVersion', $CompilerVersion) }

if ($IdeVersion) {
  $buildArguments += @('-IdeVersion', $IdeVersion) }

& $powerShell -NoProfile -File (Join-Path $PSScriptRoot 'build.ps1') @buildArguments

if ($LASTEXITCODE -ne 0) {
  throw "Build failed (exit $LASTEXITCODE). No installers were generated by this run." }

$packagingArguments = @{
  Configuration = $Configuration; Runtime = $Runtime; OptimizationPreference = $OptimizationPreference
  CliPublishDirectory = Join-Path $PSScriptRoot 'publish'
  Destination = Join-Path $PSScriptRoot 'publish'
}

if ($CompilerVersion) {
  $packagingArguments.CompilerVersion = $CompilerVersion }

if ($IdeVersion) {
  $packagingArguments.IdeVersion = $IdeVersion }

& (Join-Path $PSScriptRoot 'installer/build-installers.ps1') @packagingArguments
