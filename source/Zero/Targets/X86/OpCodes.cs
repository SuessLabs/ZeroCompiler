  /// <summary>Search for Mnemonic in list of available OpCodes.</summary>
  /// <param name="mnemonic">Search for.</param>
  /// <returns>Value or null.</returns>
  public static OpCode32? Find(string mnemonic)
  {
    foreach (var opCode in OpCodes)
      if (opCode.Name.Equals(mnemonic))
        return opCode;

    return null;
  }
